// An editor-chrome code block. `code` and `sql` are pre-highlighted HTML built
// with the token helpers above. When `sql` is present the block gets a
// "Show SQL" toggle that reveals the generated SQL, like the landing editor.
// When `copy` is present the block gets a "Copy" button: pass a plain-text
// string to copy exactly that, or `true` to copy the block's code (derived by
// stripping the highlight markup; with variants, the visible variant's code).
// `variants` ([{label, code, copy?, selected?}]) replaces `code` with several
// switchable snippets and puts a selector in the title bar; every variant is
// pre-rendered as its own pane so switching is a pure display toggle.
export function editor({file, tag, code, sql, copy, variants}) {
  // The highlighted HTML is entirely esc()'d text inside spans, so dropping
  // the tags and unescaping recovers the source text exactly.
  const toPlain = (html) => {
    // Strip tags to a fixed point before unescaping: a single pass is not idempotent, since removing an
    // inner tag can splice two fragments into a fresh tag, so repeat until the markup stops changing.
    let stripped = html;
    let previous;
    do {
      previous = stripped;
      stripped = stripped.replace(/<[^>]+>/g, '');
    } while (stripped !== previous);
    return stripped.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
  };
  // Newlines only occur in the escaped text tokens, never inside tag markup,
  // so the line count can be taken from the HTML string directly.
  const pane = (html) => {
    const lines = html.split('\n').length;
    let gutter = '';
    for (let i = 1; i <= lines; i++) gutter += `<div>${i}</div>`;
    return `<div class="gutter">${gutter}</div>
    <pre class="code">${html}</pre>`;
  };
  const selectedIdx = variants ? Math.max(0, variants.findIndex((v) => v.selected)) : 0;
  const varSel = variants
    ? `<span class="varwrap"><select class="varsel" aria-label="Snippet variant">${variants
        .map((v, i) => `<option value="${i}"${i === selectedIdx ? ' selected' : ''}>${esc(v.label)}</option>`)
        .join('')}</select></span>`
    : '';
  // Per-variant SQL: a variant may carry its own `sql` (e.g. jOOQ's MULTISET or
  // multi-row insert), otherwise it falls back to the shared `sql`. The Show SQL
  // panel then switches with the selected variant.
  const hasVariantSql = variants && variants.some((v) => v.sql);
  const hasSql = Boolean(sql) || hasVariantSql;
  const sqlBtn = hasSql
    ? `<span class="sqlbtn" role="button" tabindex="0" aria-expanded="false"><svg class="ico" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><ellipse cx="12" cy="5" rx="8" ry="3"/><path d="M4 5v14c0 1.7 3.6 3 8 3s8-1.3 8-3V5"/><path d="M4 12c0 1.7 3.6 3 8 3s8-1.3 8-3"/></svg><span class="sqlbtntext">Show SQL</span></span>`
    : '';
  const copyText =
    copy === true ? toPlain(variants ? variants[selectedIdx].code : code) : copy;
  const copyBtn = copyText
    ? `<span class="copybtn" data-copy="${esc(copyText).replace(/"/g, '&quot;')}"><svg class="ico" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><rect x="9" y="9" width="12" height="12" rx="2"/><path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"/></svg><span class="copybtntext">Copy</span></span>`
    : '';
  const sqlConsole = hasSql
    ? `<div class="sqlhead"><span class="ar">↳</span> generated sql</div><div class="sqlconsole">${
        hasVariantSql
          ? variants.map((v, i) => `<pre class="sqlpanel sqlpane${i === selectedIdx ? ' on' : ''}">${v.sql || sql || ''}</pre>`).join('')
          : `<pre class="sqlpanel">${sql}</pre>`
      }</div>`
    : '';
  const codeareas = variants
    ? variants
        .map((v, i) => {
          const paneCopy = v.copy || (copy === true ? toPlain(v.code) : null);
          return `<div class="codearea varpane${i === selectedIdx ? ' on' : ''}"${
            paneCopy ? ` data-copy="${esc(paneCopy).replace(/"/g, '&quot;')}"` : ''
          }${v.tag ? ` data-tag="${esc(v.tag).replace(/"/g, '&quot;')}"` : ''}${v.file ? ` data-file="${esc(v.file).replace(/"/g, '&quot;')}"` : ''}>${pane(v.code)}</div>`;
        })
        .join('')
    : `<div class="codearea">${pane(code)}</div>`;
  return `
<div class="editor">
  <div class="ebar">
    <span class="dot r"></span><span class="dot y"></span><span class="dot g"></span>
    <span class="fname">${esc((variants && variants[selectedIdx] && variants[selectedIdx].file) || file || '')}</span>
    <span class="langtag">${esc((variants && variants[selectedIdx] && variants[selectedIdx].tag) || tag || '')}</span>
    ${varSel}${sqlBtn}${copyBtn}
  </div>
  ${codeareas}
  ${sqlConsole}
</div>`;
}

// A one-line "$ <command>" shell bar with a Copy button, matching the editor
// copy control. `command` is copied verbatim (without the leading $). Wired by
// wireSqlToggles(), so pages that render a clonebar() must call it in useEffect.
