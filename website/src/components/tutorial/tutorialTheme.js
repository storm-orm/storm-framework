// Wires one .copybtn: copies its data-copy to the clipboard and flips the label
// to "Copied" for a moment. Returns a cleanup function.
function attachCopy(copyBtn) {
  const txt = copyBtn.querySelector('.copybtntext');
  let timer = null;
  const onCopy = () => {
    const text = copyBtn.dataset.copy;
    // The Clipboard API needs a secure context; fall back to a throwaway
    // textarea so copy also works on plain-http previews (e.g. LAN).
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text);
    } else {
      const ta = document.createElement('textarea');
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      ta.remove();
    }
    copyBtn.classList.add('on');
    if (txt) txt.textContent = 'Copied';
    clearTimeout(timer);
    timer = setTimeout(() => {
      copyBtn.classList.remove('on');
      if (txt) txt.textContent = 'Copy';
    }, 1600);
  };
  copyBtn.addEventListener('click', onCopy);
  return () => {
    copyBtn.removeEventListener('click', onCopy);
    clearTimeout(timer);
  };
}

// Wires up every "Show SQL" and "Copy" button rendered by editor(), plus the
// Copy button on any clonebar(). Returns a cleanup function for the calling
// useEffect.
export function wireSqlToggles() {
  const cleanups = [];
  document.querySelectorAll('.storm-tut .editor').forEach((ed) => {
    const btn = ed.querySelector('.sqlbtn');
    if (btn) {
      const txt = btn.querySelector('.sqlbtntext');
      const onClick = () => {
        const on = ed.classList.toggle('show-sql');
        btn.classList.toggle('on', on);
        btn.setAttribute('aria-expanded', on ? 'true' : 'false');
        if (txt) txt.textContent = on ? 'Hide SQL' : 'Show SQL';
      };
      const onKey = (e) => {
        if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); onClick(); }
      };
      btn.addEventListener('click', onClick);
      btn.addEventListener('keydown', onKey);
      cleanups.push(() => { btn.removeEventListener('click', onClick); btn.removeEventListener('keydown', onKey); });
    }
    const copyBtn = ed.querySelector('.copybtn');
    if (copyBtn) cleanups.push(attachCopy(copyBtn));
    const sel = ed.querySelector('.varsel');
    if (sel) {
      const panes = ed.querySelectorAll('.varpane');
      const sqlPanes = ed.querySelectorAll('.sqlpane');
      const onChange = () => {
        const idx = Number(sel.value);
        panes.forEach((p, i) => p.classList.toggle('on', i === idx));
        sqlPanes.forEach((p, i) => p.classList.toggle('on', i === idx));
        // A variant can carry its own copy text (data-copy on the pane).
        const cp = ed.querySelector('.copybtn');
        if (cp && panes[idx] && panes[idx].dataset.copy) cp.dataset.copy = panes[idx].dataset.copy;
        // A variant can carry its own language tag (data-tag on the pane).
        const lt = ed.querySelector('.langtag');
        if (lt && panes[idx] && panes[idx].dataset.tag) lt.textContent = panes[idx].dataset.tag;
        // A variant can carry its own filename (data-file on the pane).
        const fn = ed.querySelector('.fname');
        if (fn && panes[idx] && panes[idx].dataset.file) fn.textContent = panes[idx].dataset.file;
      };
      sel.addEventListener('change', onChange);
      cleanups.push(() => sel.removeEventListener('change', onChange));
    }
  });
  document.querySelectorAll('.storm-tut .clonebar .copybtn').forEach((copyBtn) => {
    cleanups.push(attachCopy(copyBtn));
  });
  return () => cleanups.forEach((fn) => fn());
}

